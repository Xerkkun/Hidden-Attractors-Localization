"""Bandt--Pompe ordinal-pattern distributions and permutation entropy.

Stability: experimental

This module implements a deterministic local estimator for scalar sampled
signals.  It supports trajectories generated by integer or fractional solvers
through :class:`~hidden_attractors.analysis.contracts.TrajectoryInput`, while
retaining sampling, projection, derivative, order, prehistory, and memory
provenance.  A finite plug-in entropy is a data diagnostic; it is not proof of
Kolmogorov--Sinai entropy, chaos, attraction, or hiddenness.

References
----------
C. Bandt and B. Pompe, "Permutation Entropy: A Natural Complexity Measure for
Time Series," Physical Review Letters 88 (2002), 174102.
https://doi.org/10.1103/PhysRevLett.88.174102

V. A. Unakafova and K. Keller, "Efficiently Measuring Complexity on the Basis
of Real-World Data," Entropy 15 (2013), 4392--4415.
https://doi.org/10.3390/e15104392

F. Traversaro et al., "Bandt--Pompe Symbolization Dynamics for Time Series
with Tied Values: A Data-Driven Approach," Chaos 28 (2018), 075502.
https://doi.org/10.1063/1.5022021

A. A. Rey et al., "The Asymptotic Distribution of the Permutation Entropy,"
Chaos 33 (2023), 113108. https://doi.org/10.1063/5.0171508
"""

