def permutation_entropy_from_distribution(
    distribution: OrdinalPatternDistribution,
    *,
    log_base: float = 2.0,
) -> PermutationEntropyResult:
    """Compute plug-in Shannon entropy from an existing pattern distribution."""

    if not isinstance(distribution, OrdinalPatternDistribution):
        raise TypeError("distribution must be an OrdinalPatternDistribution.")
    if isinstance(log_base, (bool, np.bool_)):
        raise TypeError("log_base must be a real number greater than one.")
    try:
        base = float(log_base)
    except (TypeError, ValueError) as exc:
        raise TypeError("log_base must be a real number greater than one.") from exc
    if not np.isfinite(base) or base <= 1.0:
        raise ValueError("log_base must be finite and greater than one.")

    positive = distribution.probabilities[distribution.probabilities > 0.0]
    logarithm = math.log(base)
    entropy = float(-np.sum(positive * np.log(positive)) / logarithm)
    maximum_entropy = float(math.log(distribution.possible_patterns) / logarithm)
    normalized_entropy = float(entropy / maximum_entropy)
    if -2e-15 <= normalized_entropy < 0.0:
        normalized_entropy = 0.0
    if 1.0 < normalized_entropy <= 1.0 + 2e-15:
        normalized_entropy = 1.0

    return PermutationEntropyResult(
        distribution=distribution,
        entropy=entropy,
        normalized_entropy=normalized_entropy,
        maximum_entropy=maximum_entropy,
        log_base=base,
        warnings=distribution.warnings,
        metadata={
            "formula": "-sum(p*log_base(p)) for p>0",
            "normalization_denominator": (
                "log_base(factorial(embedding_dimension))"
            ),
            "finite_sample_bias_correction": "none",
        },
    )


def permutation_entropy(
    data: Sequence[float] | np.ndarray | TrajectoryInput,
    *,
    component: int | str | None = None,
    embedding_dimension: int = 3,
    delay: int = 1,
    tie_policy: TiePolicy = "stable_index",
    log_base: float = 2.0,
    backend: Backend = "auto",
    fallback: bool = True,
    sampling: str = "sample index",
    projection: str = "supplied scalar signal",
) -> PermutationEntropyResult:
    """Estimate a Bandt--Pompe distribution and its plug-in Shannon entropy."""

    distribution = ordinal_pattern_distribution(
        data,
        component=component,
        embedding_dimension=embedding_dimension,
        delay=delay,
        tie_policy=tie_policy,
        backend=backend,
        fallback=fallback,
        sampling=sampling,
        projection=projection,
    )
    return permutation_entropy_from_distribution(distribution, log_base=log_base)


